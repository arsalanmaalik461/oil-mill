final _df = DateFormat('dd MMM yyyy, hh:mm a');

pw.Widget _header(Business business, String title) {
  return pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.start,
    children: [
      pw.Text(business.name,
          style: pw.TextStyle(fontSize: 20, fontWeight: pw.FontWeight.bold, color: PdfColor.fromHex('#EE4023'))),
      if (business.owner.isNotEmpty) pw.Text('Owner: ${business.owner}'),
      if (business.phone.isNotEmpty) pw.Text('Phone: ${business.phone}'),
      if (business.address.isNotEmpty) pw.Text('Address: ${business.address}'),
      pw.SizedBox(height: 6),
      pw.Text(title, style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold)),
      pw.Divider(color: PdfColor.fromHex('#EE4023')),
    ],
  );
}

pw.Widget _footer() => pw.Padding(
      padding: const pw.EdgeInsets.only(top: 8),
      child: pw.Text('Generated by Namat Oil Mill app',
          style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey)),
    );

Future<void> shareLedgerPdf({
  required Business business,
  required Party party,
  required List<PartyTransaction> transactions,
  required double balance,
}) async {
  final doc = pw.Document();
  double running = party.openingBalance;
  final rows = <List<String>>[];
  // Ascending chronological order with an id tiebreak (Dart's sort is not
  // stable): bill-created udhaar/wasool pairs share one timestamp, and the
  // running balance is only correct if udhaar is applied first, matching
  // the on-screen ledger in party_detail_screen.
  final sorted = [...transactions]..sort((a, b) {
      final c = a.dateTime.compareTo(b.dateTime);
      return c != 0 ? c : (a.id ?? 0).compareTo(b.id ?? 0);
    });
  for (final t in sorted) {
    running += t.type == 'udhaar' ? t.amount : -t.amount;
    rows.add([
      _df.format(t.dateTime),
      t.type == 'udhaar' ? 'Udhaar (Gave)' : 'Wasool (Got)',
      t.note,
      formatRs(t.amount),
      formatRs(running),
    ]);
  }
  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    build: (c) => [
      _header(business, 'Ledger — ${party.name}'),
      pw.Text('Phone: ${party.phone}'),
      pw.Text('Opening Balance: ${formatRs(party.openingBalance)}'),
      pw.SizedBox(height: 10),
      pw.TableHelper.fromTextArray(
        headers: ['Date', 'Type', 'Note', 'Amount', 'Balance'],
        data: rows,
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
        headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#EE4023')),
        cellStyle: const pw.TextStyle(fontSize: 9),
      ),
      pw.SizedBox(height: 10),
      pw.Text(
        balance >= 0 ? 'You will get: ${formatRs(balance)}' : 'You will give: ${formatRs(-balance)}',
        style: pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold),
      ),
      _footer(),
    ],
  ));
  await Printing.sharePdf(bytes: await doc.save(), filename: 'ledger_${party.name}.pdf');
}

Future<void> shareBillPdf({
  required Business business,
  required Bill bill,
  required List<BillItem> items,
}) async {
  final doc = pw.Document();
  doc.addPage(pw.Page(
    pageFormat: PdfPageFormat.a4,
    build: (c) => pw.Column(
      crossAxisAlignment: pw.CrossAxisAlignment.start,
      children: [
        _header(business, 'Invoice — Bill #${bill.billNo}'),
        pw.Text('Date: ${_df.format(bill.dateTime)}'),
        pw.Text('Customer: ${bill.partyName.isNotEmpty ? bill.partyName : 'Cash Customer'}'),
        pw.Text('Status: ${bill.status == 'paid' ? 'PAID' : 'PENDING'}'),
        pw.SizedBox(height: 10),
        pw.TableHelper.fromTextArray(
          headers: ['Item', 'Qty', 'Rate', 'Amount'],
          data: items
              .map((i) => [i.name, formatQty(i.qty), formatRs(i.rate), formatRs(i.amount)])
              .toList(),
          headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
          headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#EE4023')),
          cellStyle: const pw.TextStyle(fontSize: 10),
        ),
        pw.SizedBox(height: 10),
        pw.Align(
          alignment: pw.Alignment.centerRight,
          child: pw.Text('TOTAL: ${formatRs(bill.total)}',
              style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold)),
        ),
        pw.Spacer(),
        pw.Text('Thank you for your business!',
            style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey)),
        _footer(),
      ],
    ),
  ));
  await Printing.sharePdf(bytes: await doc.save(), filename: 'bill_${bill.billNo}.pdf');
}

Future<void> shareReportPdf({
  required Business business,
  required String title,
  required List<String> headers,
  required List<List<String>> rows,
  String? summaryLine,
}) async {
  final doc = pw.Document();
  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    build: (c) => [
      _header(business, title),
      pw.SizedBox(height: 8),
      pw.TableHelper.fromTextArray(
        headers: headers,
        data: rows,
        headerStyle: pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
        headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#EE4023')),
        cellStyle: const pw.TextStyle(fontSize: 9),
      ),
      if (summaryLine != null) ...[
        pw.SizedBox(height: 10),
        pw.Text(summaryLine, style: pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
      ],
      _footer(),
    ],
  ));
  await Printing.sharePdf(
      bytes: await doc.save(), filename: '${title.replaceAll(' ', '_').toLowerCase()}.pdf');
}

/// Builds the FULL ledger PDF for a business (all parties) and returns
/// the raw bytes — used for the Google Drive upload (Settings) instead
/// of the share sheet. Layout: header, a summary table of every party,
/// then one ledger section per party that has transactions or a
/// non-zero balance.
Future<Uint8List> buildFullLedgerPdfBytes({
  required Business business,
  required List<Party> parties,
  required Map<int, double> balances,
  required Map<int, List<PartyTransaction>> transactionsByParty,
}) async {
  final doc = pw.Document();

  double balanceOf(Party party) =>
      party.id == null ? party.openingBalance : (balances[party.id] ?? party.openingBalance);

  String balanceText(double b) =>
      b >= 0 ? 'You will get: ${formatRs(b)}' : 'You will give: ${formatRs(-b)}';

  // ---- Summary table: every party -------------------------------------
  final sortedParties = [...parties]
    ..sort((a, b) => a.name.toLowerCase().compareTo(b.name.toLowerCase()));
  final summaryRows = <List<String>>[];
  double totalGet = 0;
  double totalGive = 0;
  for (final party in sortedParties) {
    final b = balanceOf(party);
    if (b > 0) totalGet += b;
    if (b < 0) totalGive += -b;
    summaryRows.add([
      party.name,
      party.phone,
      formatRs(b),
      b > 0 ? 'You will get' : (b < 0 ? 'You will give' : 'Settled'),
    ]);
  }

  final children = <pw.Widget>[
    _header(business, 'Full Ledger — All Parties'),
    pw.Text('Generated: ${_df.format(DateTime.now())}'),
    pw.SizedBox(height: 10),
    pw.Text('Summary', style: const pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold)),
    pw.SizedBox(height: 6),
    pw.TableHelper.fromTextArray(
      headers: ['Name', 'Phone', 'Balance', 'Status'],
      data: summaryRows,
      headerStyle: const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
      headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#EE4023')),
      cellStyle: const pw.TextStyle(fontSize: 9),
    ),
    pw.SizedBox(height: 8),
    pw.Text('Total you will get: ${formatRs(totalGet)}',
        style: const pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
    pw.Text('Total you will give: ${formatRs(totalGive)}',
        style: const pw.TextStyle(fontSize: 11, fontWeight: pw.FontWeight.bold)),
  ];

  // ---- One section per party with activity or a balance ---------------
  for (final party in sortedParties) {
    final transactions =
        party.id == null ? const <PartyTransaction>[] : (transactionsByParty[party.id] ?? const <PartyTransaction>[]);
    final balance = balanceOf(party);
    if (transactions.isEmpty && balance == 0) continue;

    double running = party.openingBalance;
    final rows = <List<String>>[];
    // Same ordering logic as shareLedgerPdf: ascending date with an id
    // tiebreak so the running balance matches the on-screen ledger.
    final sorted = [...transactions]..sort((a, b) {
        final c = a.dateTime.compareTo(b.dateTime);
        return c != 0 ? c : (a.id ?? 0).compareTo(b.id ?? 0);
      });
    for (final t in sorted) {
      running += t.type == 'udhaar' ? t.amount : -t.amount;
      rows.add([
        _df.format(t.dateTime),
        t.type == 'udhaar' ? 'Udhaar (Gave)' : 'Wasool (Got)',
        t.note,
        formatRs(t.amount),
        formatRs(running),
      ]);
    }

    children.addAll([
      pw.SizedBox(height: 16),
      pw.Text(party.name, style: const pw.TextStyle(fontSize: 13, fontWeight: pw.FontWeight.bold)),
      if (party.phone.isNotEmpty) pw.Text('Phone: ${party.phone}'),
      pw.Text('Opening Balance: ${formatRs(party.openingBalance)}'),
      pw.SizedBox(height: 6),
      if (rows.isNotEmpty)
        pw.TableHelper.fromTextArray(
          headers: ['Date', 'Type', 'Note', 'Amount', 'Balance'],
          data: rows,
          headerStyle: const pw.TextStyle(fontWeight: pw.FontWeight.bold, color: PdfColors.white),
          headerDecoration: pw.BoxDecoration(color: PdfColor.fromHex('#EE4023')),
          cellStyle: const pw.TextStyle(fontSize: 9),
        ),
      pw.SizedBox(height: 6),
      pw.Text(balanceText(balance),
          style: const pw.TextStyle(fontSize: 12, fontWeight: pw.FontWeight.bold)),
    ]);
  }

  children.add(_footer());
  doc.addPage(pw.MultiPage(
    pageFormat: PdfPageFormat.a4,
    build: (c) => children,
  ));
  return doc.save();
}
